import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';

const bank = JSON.parse(readFileSync(new URL('../seed-data/banks/kedkel-2026-tryout-1.json', import.meta.url), 'utf8'));
const bank2 = JSON.parse(readFileSync(new URL('../seed-data/banks/kedkel-2026-tryout-2.json', import.meta.url), 'utf8'));
const manifest = JSON.parse(readFileSync(new URL('../seed-data/manifest.json', import.meta.url), 'utf8'));
const materiCode = readFileSync(new URL('../js/kedkel-2026-materi.js', import.meta.url), 'utf8');

function loadModule() {
  const ctx = { window: {}, document: { getElementById: () => null, addEventListener: () => {} } };
  vm.runInNewContext(materiCode, ctx);
  return ctx.window.CLINED_KEDKEL_2026_MATERI;
}

test('seed-data/manifest.json mendaftarkan TRY OUT 1 & 2 KEDKEL by Reza (masing-masing 100 soal)', () => {
  const entry1 = manifest.banks.find(b => b.id === 'kedkel-2026-tryout-1');
  assert.ok(entry1);
  assert.equal(entry1.name, 'TRY OUT 1 KEDKEL by Reza (generated by AI based on all materi)');
  assert.equal(entry1.block, 'KEDKEL');
  assert.equal(entry1.count, 100);

  const entry2 = manifest.banks.find(b => b.id === 'kedkel-2026-tryout-2');
  assert.ok(entry2);
  assert.equal(entry2.name, 'TRY OUT 2 KEDKEL by Reza (generated by AI based on all materi)');
  assert.equal(entry2.block, 'KEDKEL');
  assert.equal(entry2.count, 100);
});

test('100 soal Try Out Kedkel 2026 (Paket 1 & Paket 2) terpetakan lengkap ke 31 materi PPT Google Drive', () => {
  const mod = loadModule();
  assert.equal(mod.TOPICS.length, 31);
  assert.equal(mod.TOPICS.reduce((s, t) => s + t.count, 0), 100);
  assert.equal(mod.TOPICS.reduce((s, t) => s + t.weightPct, 0), 100);
  assert.equal(mod.hasBobotForBank('kedkel-2026-tryout-1'), true);
  assert.equal(mod.hasBobotForBank('kedkel-2026-tryout-2'), true);

  for (const [bankId, list] of [['kedkel-2026-tryout-1', bank], ['kedkel-2026-tryout-2', bank2]]) {
    assert.equal(list.length, 100);
    const seenNos = new Set();
    for (const q of list) {
      assert.ok(q.no >= 1 && q.no <= 100);
      assert.equal(q.source_id, q.no);
      assert.ok(!seenNos.has(q.no));
      seenNos.add(q.no);
      assert.equal(q.opsi.length, 5);
      assert.ok(Number.isInteger(q.jawabanBenar) && q.jawabanBenar >= 0 && q.jawabanBenar < 5);
      assert.ok(q.pembahasan && q.pembahasan.length > 20);
      assert.equal(q.pembahasanPilihan.length, 5);
      assert.ok(q.materiNo >= 1 && q.materiNo <= 31);
      assert.match(q.materiPptUrl, /^https:\/\/(drive|docs)\.google\.com\//);
      assert.match(q.materiFolderUrl, /^https:\/\/drive\.google\.com\/drive\/folders\//);
      assert.ok(Array.isArray(q.materiFiles) && q.materiFiles.length >= 1);

      const resolved = mod.forQuestion({ id: q.id, no: q.no, bank: bankId });
      assert.equal(resolved.materiNo, q.materiNo);
      assert.equal(resolved.materiPptUrl, q.materiPptUrl);
      assert.ok(mod.renderPptBarHTML(q, 'quiz').includes('Materi PPT:'));
      assert.ok(mod.renderPptBarHTML(q, 'explain').includes(q.materiPptUrl.replace(/&/g, '&amp;')));
    }
    assert.equal(seenNos.size, 100);
  }
});

test('buildLatihanMateriPacks membangun 31 paket materi KEDKEL (100 soal Paket 1 / 200 soal Paket 1+2)', () => {
  const mod = loadModule();
  const packs1 = mod.buildLatihanMateriPacks(bank);
  assert.equal(packs1.length, 31);
  assert.equal(packs1.reduce((n, p) => n + p.questions.length, 0), 100);

  const packsCombined = mod.buildLatihanMateriPacks([...bank, ...bank2]);
  assert.equal(packsCombined.length, 31);
  assert.equal(packsCombined.reduce((n, p) => n + p.questions.length, 0), 200);
  for (const p of packsCombined) {
    assert.equal(p.block, 'KEDKEL');
    assert.ok(p.materiPptUrl);
    assert.ok(p.questions.every(q => Array.isArray(q.pembahasanPilihan) && q.pembahasanPilihan.length === 5));
  }
});
